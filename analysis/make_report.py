CAL = np.array([-4.19292717e-03, 6.50323880e+00, 1.58616071e+02])
def px2cm(y):
    r = np.roots([CAL[0], CAL[1], CAL[2] - y]); r = r[np.isreal(r)].real
    return float(r.min())

cf = (141.3, 3.16, 5.91); cb = (924.8, -41.25, 6.13)
S, FPS = 5.70, 30.0
